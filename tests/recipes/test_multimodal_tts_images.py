def _images() -> catalog.TaskImages:
    return catalog.task_images(TASK)


def _baseline() -> LayerImage:
    declared = catalog.image_set(TASK).baseline
    assert declared is not None and isinstance(declared.image, LayerImage)
    return declared.image


def _locked(decl) -> dict[str, str]:
    return lock_pip.pins_of((lock_dir(decl, pins.LOCKS_DIR) / decl.pip_lock).read_text())


def test_the_task_declares_its_baseline_alone():
    images = _images()
    assert images.measured == {"baseline": "multimodal-tts-baseline"}
    assert [d.name for d in images.decls] == ["s-a", "s-a-tf-4-57-3-qwen-tts", "s-a-tf-4-57-3-qwen-tts-agent", "cuda",
                                              "cuda-setuptools", "multimodal-tts-baseline"]


def test_the_baseline_is_a_server_layer_of_the_task_on_the_setuptools_layer():
    baseline = _baseline()
    assert (baseline.parent, baseline.owner, baseline.server) == ("cuda-setuptools", TASK, True)
    assert (baseline.pip_lock, baseline.apt_lock) == ("baseline.txt", None)
    assert baseline.files == {"/app/server_vllm_omni.py": "server_vllm_omni.py",
                              "/app/omni_codes_spool.py": "omni_codes_spool.py"}


def test_the_baseline_lock_pins_the_serving_stack():
    locked = _locked(_baseline())
    assert {name: locked.get(name) for name in ENGINE} == ENGINE
    # The build backend is the layer's below, not the lock's own.
    assert "setuptools" not in locked
    below = catalog.SHARED["cuda-setuptools"]
    assert isinstance(below, LayerImage) and _locked(below) == {"setuptools": "80.10.2"}


def test_the_baseline_lock_says_how_it_was_compiled_and_hashes_every_package():
    baseline = _baseline()
    text = (lock_dir(baseline, pins.LOCKS_DIR) / baseline.pip_lock).read_text()
    args = lock_pip.arguments("layer", "baseline", task=TASK, parent="layer-cuda-setuptools",
                              source_builds=sorted(pip_name(pin) for pin in baseline.source_builds), server=True)
    assert text.splitlines()[0] == f"# Generated by: {lock_pip.COMMAND} {' '.join(args)}"
    assert text.splitlines()[1] == lock_pip.header(args).splitlines()[1]
    blocks = lock_pip.blocks(text)
    assert len(blocks) == 240
    assert all("--hash=sha256:" in lines for _, _, lines in blocks)
    # The command line the lock's input names is the one that compiled it.
    assert f"#   {lock_pip.COMMAND} {' '.join(args)}\n" in (TASK_DIR / "locks" / "baseline.in").read_text()


def test_the_baseline_lock_is_its_input_and_nothing_else():
    """The input names every package of the stack at one version, so the lock resolves nothing:
    it pins exactly the input's packages, each at the input's version."""
    lines = [line for line in (TASK_DIR / "locks" / "baseline.in").read_text().splitlines()
             if line and not line.startswith("#")]
    named = [re.fullmatch(r"([a-z0-9][a-z0-9-]*)==(\S+)", line) for line in lines]
    assert all(named), [line for line, m in zip(lines, named, strict=True) if not m]
    assert lines == sorted(lines, key=lambda line: line.split("==")[0])
    assert dict(m.groups() for m in named) == _locked(_baseline())


def test_the_packages_published_as_source_alone_build_against_the_layer_below():
    """openai-whisper and antlr4-python3-runtime have no wheel: each is locked by the one hash of
    its source distribution and built in the venv, against the setuptools of the layer below."""
    baseline = _baseline()
    assert baseline.source_builds == {"antlr4-python3-runtime==4.9.3": ["setuptools"],
                                      "openai-whisper==20250625": ["setuptools"]}
    check_source_builds(_images().decls, pins.LOCKS_DIR)
    text = (lock_dir(baseline, pins.LOCKS_DIR) / baseline.pip_lock).read_text()
    hashes = {name: lines.count("--hash=sha256:") for name, _, lines in lock_pip.blocks(text)}
    assert (hashes["antlr4-python3-runtime"], hashes["openai-whisper"]) == (1, 1)
    rendered = render_def(baseline, parent_sif=Path("/node/parent.sif"), locks=pins.LOCKS_DIR, uv=pins.UV)
    assert ("--only-binary :all: --no-binary antlr4-python3-runtime --no-build-isolation-package "
            "antlr4-python3-runtime --no-binary openai-whisper --no-build-isolation-package openai-whisper "
            ) in rendered
    assert "--require-hashes --no-deps" in rendered


def test_the_baseline_renders_with_its_lock_and_both_server_files():
    images = _images()
    baseline = _baseline()
    keys = image_keys(images.decls, recipe_key)
    assert re.fullmatch(r"multimodal-tts-baseline-[0-9a-f]{16}", keys["multimodal-tts-baseline"])
    files = files_for(baseline, pins.LOCKS_DIR)
    assert files == {"/app/omni_codes_spool.py": TASK_DIR / "omni_codes_spool.py",
                     "/app/server_vllm_omni.py": TASK_DIR / "server_vllm_omni.py",
                     "/opt/hls/locks/baseline.txt": TASK_DIR / "locks" / "baseline.txt"}
    assert all(path.is_file() for path in files.values())
    rendered = render_def(baseline, parent_sif=Path("/node/parent.sif"), locks=pins.LOCKS_DIR, uv=pins.UV)
    assert rendered.startswith("Bootstrap: localimage\nFrom: /node/parent.sif\n")
    for container, host in files.items():
        assert f"    {host} {container}\n" in rendered
    # The build downloads nothing but its lock's packages.
    assert "curl" not in rendered and "wget" not in rendered


def test_the_baseline_bakes_the_environment_its_measured_image_baked():
    images = _images()
    # With the shared base's constraint variables, which name its empty constraints file; the
    # layer itself sets only what the base does not give.
    shared = {"UV_CONSTRAINT": "/opt/hls/constraints.txt", "PIP_CONSTRAINT": "/opt/hls/constraints.txt"}
    assert baked_environment("multimodal-tts-baseline", images.decls) == {**BAKED, **shared}
    rendered = render_def(_baseline(), parent_sif=Path("/node/parent.sif"), locks=pins.LOCKS_DIR, uv=pins.UV)
    section = rendered.split("%environment\n", 1)[1].split("\n\n", 1)[0]
    assert section.splitlines() == ["    export UV_TORCH_BACKEND=cu130", "    export TORCH_CUDA_ARCH_LIST=9.0"]


def test_the_baseline_starts_as_the_task_declares():
    declared = catalog.image_set(TASK).baseline
    assert (declared.entrypoint, declared.runtime_env) == (["python", "/app/server_vllm_omni.py"], {})

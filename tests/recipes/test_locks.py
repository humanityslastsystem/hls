class FakeRun:
    """Stands in for ``subprocess.run`` of uv: ``uv --version`` prints *version*; ``uv pip
    compile`` is recorded and writes the output file it names."""

    def __init__(self, version: str = "uv 0.11.16 (x86_64-unknown-linux-gnu)\n") -> None:
        self.version = version
        self.calls: list[dict] = []
        self.asked: list[dict] = []

    def __call__(self, argv, *, cwd=None, env, capture_output, text):
        if argv[1:] == ["--version"]:
            self.asked.append({"argv": argv, "env": env})
            return subprocess.CompletedProcess(argv, 0, self.version, "")
        self.calls.append({"argv": argv, "cwd": Path(cwd), "env": env,
                           "files": sorted(p.name for p in Path(cwd).iterdir())})
        Path(cwd, argv[argv.index("-o") + 1]).write_text("x==1 \\\n    --hash=sha256:aa\n    # via -r y.in\n")
        return subprocess.CompletedProcess(argv, 0, "", "")



def test_resolve_takes_the_highest_version_across_pockets_and_refuses_an_unknown_name():
    release = "Package: git\nVersion: 1:2.43.0-1ubuntu7\n\nPackage: jq\nVersion: 1.7.1-3build1\n"
    updates = "Package: git\nVersion: 1:2.43.0-1ubuntu7.3\n"

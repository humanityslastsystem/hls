def _npm_main(tmp_path, monkeypatch, lock: bytes) -> tuple[Path, dict]:
    """A copy of the committed locks, fakes for the unpacked Node and its versions, and the
    arguments that stand in for the download and for npm resolving *lock*."""
    locks = tmp_path / "locks"
    locks.mkdir()
    for path in LOCKS.iterdir():
        locks.joinpath(path.name).write_bytes(path.read_bytes())
    monkeypatch.setattr(lock_npm, "unpack_node", lambda data, pin, dest: dest)
    monkeypatch.setattr(lock_npm, "versions", lambda home: ("v22.23.3", "10.9.9"))
    return locks, {"locks": locks, "fetch": lambda pin: b"", "resolve": lambda manifest, home, work: lock}


def test_an_npm_lock_the_renderer_would_refuse_is_never_written(tmp_path, monkeypatch):
    committed = (LOCKS / "npm-agent.json").read_bytes()
    lock = json.loads(committed)
    lock["packages"][""]["dependencies"]["left-pad"] = "1.3.0"
    locks, given = _npm_main(tmp_path, monkeypatch, json.dumps(lock).encode())
    with pytest.raises(LockRefused, match="the renderer refuses it: .* does not depend on exactly"):
        lock_npm.lock_npm("npm-agent.json", **given)
    assert (locks / "npm-agent.json").read_bytes() == committed


def test_the_npm_lock_is_written_once_the_renderer_accepts_it(tmp_path, monkeypatch):
    committed = (LOCKS / "npm-agent.json").read_bytes()
    locks, given = _npm_main(tmp_path, monkeypatch, committed)
    (locks / "npm-agent.json").unlink()
    printed: list[str] = []
    assert lock_npm.lock_npm("npm-agent.json", echo=printed.append, **given) == committed
    assert (locks / "npm-agent.json").read_bytes() == committed
    assert printed == ["npm-agent.json: node v22.23.3, npm 10.9.9"]



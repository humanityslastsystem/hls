# The CUDA base's digest.

class FakeRegistry:
    """Stands in for ``urllib.request.urlopen`` of Docker Hub: the token service answers *token*,
    the manifest's HEAD the headers *headers*. Records every request."""

    def __init__(self, headers: dict[str, str], token: str = "tok-123") -> None:
        self.headers, self.token, self.requests = headers, token, []

    def __call__(self, request, timeout):
        self.requests.append(request)
        if isinstance(request, str):
            return io.BytesIO(json.dumps({"token": self.token}).encode())
        response = io.BytesIO(b"")
        response.headers = self.headers
        return response


def test_the_base_digest_is_the_tags_index_digest_asked_with_an_anonymous_token():
    digest = "sha256:" + "7d" * 32
    registry = FakeRegistry({"Docker-Content-Digest": digest})
    assert base_digest.base_reference("nvidia/cuda", "13.0.1-devel-ubuntu24.04", urlopen=registry) == (
        f"nvidia/cuda:13.0.1-devel-ubuntu24.04@{digest}")
    token_url, head = registry.requests
    assert token_url == ("https://auth.docker.io/token?service=registry.docker.io&scope=repository:"
                         "nvidia/cuda:pull")
    assert head.full_url == "https://registry-1.docker.io/v2/nvidia/cuda/manifests/13.0.1-devel-ubuntu24.04"
    assert head.get_method() == "HEAD"
    assert head.get_header("Authorization") == "Bearer tok-123"
    # The index of every platform, never one platform's manifest.
    assert head.get_header("Accept") == ("application/vnd.oci.image.index.v1+json, "
                                         "application/vnd.docker.distribution.manifest.list.v2+json")
    assert pins.CUDA_BASE.startswith("nvidia/cuda:13.0.1-devel-ubuntu24.04@sha256:")



def test_the_lock_apt_command_writes_through_the_tool_and_refuses_in_one_line(monkeypatch):
    from typer.testing import CliRunner

    from hls import cli

    seen = []
    monkeypatch.setattr(lock_apt, "lock_apt",
                        lambda repo, name, fetch, task, echo: seen.append((repo, name, fetch, task)))
    result = CliRunner().invoke(cli.app, ["images", "lock-apt", "nvidia", "apt-nvidia"])
    assert result.exit_code == 0 and seen == [("nvidia", "apt-nvidia", lock_apt.fetch_index, None)]
    result = CliRunner().invoke(cli.app, ["images", "lock-apt", "ubuntu", "apt-reference", "--task", "t"])
    assert result.exit_code == 0 and seen[1] == ("ubuntu", "apt-reference", lock_apt.fetch_index, "t")
    assert CliRunner().invoke(cli.app, ["images", "lock-apt", "debian", "apt-base"]).exit_code == 2

    def refuse(repo, name, fetch, task, echo):
        raise LockRefused("no index carries ['nope']")

    monkeypatch.setattr(lock_apt, "lock_apt", refuse)
    result = CliRunner().invoke(cli.app, ["images", "lock-apt", "ubuntu", "apt-base"])
    assert result.exit_code == 1 and result.stderr == "hls images lock-apt: no index carries ['nope']\n"



def _tarball(files: dict[str, bytes]) -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for name, data in files.items():
            info = tarfile.TarInfo(name)
            info.size = len(data)
            tar.addfile(info, io.BytesIO(data))
    return buf.getvalue()


def test_a_node_tarball_is_unpacked_only_when_it_matches_its_digest(tmp_path):
    from hls.recipes.model import NodePin

    top = "node-v22.23.3-linux-x64"
    data = _tarball({f"{top}/bin/node": b"#!/bin/sh\n", f"{top}/lib/node_modules/npm/x": b""})
    good = NodePin(version="22.23.3", sha256=hashlib.sha256(data).hexdigest())
    home = lock_npm.unpack_node(data, good, tmp_path / "a")
    assert (home / "bin" / "node").is_file()
    bad = NodePin(version="22.23.3", sha256="0" * 64)
    with pytest.raises(LockRefused, match="does not match"):
        lock_npm.unpack_node(data, bad, tmp_path / "b")
    assert not (tmp_path / "b").exists()


def test_a_node_tarball_unpacks_only_its_top_directory(tmp_path):
    from hls.recipes.model import NodePin

    top = "node-v22.23.3-linux-x64"
    data = _tarball({f"{top}/bin/node": b"node", "elsewhere/bin/node": b"other", "README": b"x"})

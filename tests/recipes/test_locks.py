class FakeCompile:
    """Stands in for ``uv pip compile``: writes *output* and records each call's arguments."""

    def __init__(self, output: str) -> None:
        self.output = output
        self.calls: list[dict] = []

    def __call__(self, src, out, *, constraints=None, omit=(), source_builds=(), exclude_newer=pins.EXCLUDE_NEWER,
                 no_deps=False):
        given = None if constraints is None else constraints.read_text()
        self.calls.append({"src": src.name, "constraints": given, "omit": omit,
                           "source_builds": source_builds, **({"no_deps": True} if no_deps else {})})
        self.exclude_newer = exclude_newer
        out.write_text(self.output)



@pytest.mark.parametrize("name", [*BASES, *LAYERS])
def test_every_pip_lock_says_how_to_regenerate_it_and_hashes_every_package(name):
    text = _text(name)
    kind = "layer" if name in LAYERS else "base"
    first = text.splitlines()[0]
    # The first line names the arguments that make the lock again.
    assert first.startswith("# Generated by: ") and f" {kind} {name}" in first
    assert pins.EXCLUDE_NEWER in text.splitlines()[1]
    # The uv that compiled it: another may format the same pins differently.
    assert f"; uv {pins.LOCK_UV};" in text.splitlines()[1]
    for pkg, version, block in lock_pip.blocks(text):
        assert "--hash=sha256:" in block, f"{name}: {pkg}=={version} has no hash"


@pytest.mark.parametrize("name", [*BASES, *LAYERS])
def test_no_lock_names_a_path_of_the_machine_that_compiled_it(name):
    # uv annotates each requirement with the file it came from, as it was given on the command line.
    sources = set(re.findall(r"#\s+(?:via )?-([rc]) (\S+)", _text(name)))
    assert sources and all(not path.startswith("/") and "/" not in path for _, path in sources), sources
    assert ("r", f"{name}.in") in sources


@pytest.mark.parametrize("name", [*BASES, *LAYERS])
def test_no_base_or_layer_holds_a_deny_listed_package(name):
    # Every layer is part of an unsealed image: its agent cap's sandbox.
    denied = {lock_pip.normalize(n) for n in DENIED_PACKAGES}
    assert not denied & set(lock_pip.pins_of(_text(name)))



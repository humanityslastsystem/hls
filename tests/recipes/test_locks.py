@pytest.mark.parametrize("name", APT)
def test_every_apt_lock_pins_exactly_its_inputs_in_order(name):
    names = lock_apt.read_names(LOCKS / f"{name}.in")
    lines = [line for line in _text(name).splitlines() if line and not line.startswith("#")]
    assert [line.split("=", 1)[0] for line in lines] == names
    pin = r"[a-z0-9][a-z0-9+.-]*=[A-Za-z0-9.+~:-]+"
    # NVIDIA's repository has no snapshot, so each of its pins also records its .deb's sha256.
    line_re = pin + (r" [0-9a-f]{64}" if name == "apt-nvidia" else "")
    assert all(re.fullmatch(line_re, line) for line in lines)



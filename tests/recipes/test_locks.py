    own.mkdir(parents=True)
    (own / "reference.in").write_text("# what the driver needs\nharbor==0.8.0\nopenai==2.54.0\n")
    shared = tmp_path / "shared"
    shared.mkdir()
    fake = FakeCompile("harbor==0.8.0 \\\n    --hash=sha256:aa\nopenai==2.54.0 \\\n    --hash=sha256:bb\n")

    def lock(name: str = "reference", **options) -> dict[str, str]:
        return _lock_pip(shared, fake, "layer", name, tasks_dir=tmp_path / "tasks", **options)

    assert lock(task="t", server=True, no_deps=True) == {"harbor": "0.8.0", "openai": "2.54.0"}

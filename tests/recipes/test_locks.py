def test_blocks_normalize_names_and_keep_each_requirements_lines():
    got = lock_pip.blocks(LOCK)
    assert [(n, v) for n, v, _ in got] == [("alpha", "1.0"), ("beta-pkg", "2.0+cu130")]
    assert got[0][2].count("--hash") == 2


def test_reduce_layer_drops_what_the_parent_pins_at_the_same_version():
    parent = "alpha==1.0 \\\n    --hash=sha256:aa\n"
    assert lock_pip.reduce_layer(LOCK, parent).startswith("Beta_Pkg==2.0+cu130")
    other = "alpha==0.9 \\\n    --hash=sha256:aa\n"
    assert "alpha==1.0" in lock_pip.reduce_layer(LOCK, other)


def test_denied_in_finds_a_deny_listed_name_in_any_spelling():
    assert lock_pip.denied_in("Flash_Attn==2.0 \\\n    --hash=sha256:aa\n") == ["flash-attn"]
    assert lock_pip.denied_in(LOCK) == []



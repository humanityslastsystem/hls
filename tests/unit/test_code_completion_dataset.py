"""Unit tests for CodeCompletionDataset (the code-completion adapter): the seeded
per-item prefix window, instruction-first prompt rendering, and the pre-rendered
single-turn item rendering it inherits from HFDataset. No network/tokenizer access
-- the window draw and the prompt text are pure, and rendering is exercised via
`items_at` on fixture rows (same shape as tests/unit/test_mmlu_pro.py)."""
from __future__ import annotations

import json
import zlib

import pytest

from hls.spec.datasets import CODE_COMPLETION_INSTRUCTION, CodeCompletionDataset, Split

_REV = "4db92d2ec0c1b4c41eeb439cfae16854511d9dcd"


def _ds(**kw) -> CodeCompletionDataset:
    return CodeCompletionDataset(revision=_REV, **kw)


# --- seeded truncation window ------------------------------------------------

def test_prefix_window_is_deterministic_for_a_given_seed_and_index():
    a = CodeCompletionDataset.prefix_tokens(1024, 3072, seed=7, idx=42)
    b = CodeCompletionDataset.prefix_tokens(1024, 3072, seed=7, idx=42)
    assert a == b


def test_prefix_window_stays_inside_its_bounds():
    draws = [CodeCompletionDataset.prefix_tokens(1024, 3072, seed=20260727, idx=i)
             for i in range(500)]
    assert min(draws) >= 1024 and max(draws) <= 3072


def test_prefix_window_varies_across_items_and_seeds():
    """Per-item variation is the point -- a single fixed prefix length would put one
    prefill size on the wire instead of a 1-3K spread."""
    per_item = {CodeCompletionDataset.prefix_tokens(1024, 3072, seed=1, idx=i)
                for i in range(200)}
    assert len(per_item) > 100
    assert (CodeCompletionDataset.prefix_tokens(1024, 3072, seed=1, idx=0)
            != CodeCompletionDataset.prefix_tokens(1024, 3072, seed=2, idx=0))


def test_degenerate_window_pins_the_length():
    assert CodeCompletionDataset.prefix_tokens(512, 512, seed=3, idx=9) == 512


# --- prompt rendering ---------------------------------------------------------

def test_prompt_is_instruction_first_so_the_instruction_is_a_shared_prefix():
    text = _ds().render_prompt("import os\n")
    assert text.startswith(CODE_COMPLETION_INSTRUCTION)
    assert text == f"{CODE_COMPLETION_INSTRUCTION}\n\nimport os\n"


def test_items_render_the_prerendered_columns_verbatim(tmp_path):
    """corpus() pre-renders prompt/target; the pass-through templates must echo them
    (the MMLUProDataset arrangement), so no rendering happens at drive time."""
    rows = [{"hash": 1, "prompt": "INSTR\n\ndef f():\n", "target": "    return 1\n"}]
    d = tmp_path / "test"
    d.mkdir()
    (d / "rows.json").write_text(json.dumps(rows))

    items = list(_ds().items_at(tmp_path, Split.TEST))
    assert len(items) == 1 and len(items[0].turns) == 1
    assert items[0].turns[0].first_of("text").text == "INSTR\n\ndef f():\n"
    assert items[0].ground_truth_turns[0] == "    return 1\n"


# --- corpus() pool shaping ---------------------------------------------------
# The stream is faked and the tokenizer stubbed through the module's own cache, so
# the filter chain (license / autogenerated / length) and the seeded truncation are
# exercised without a 142 MB download.

class _WordTokenizer:
    """Stand-in tokenizer: one token per whitespace-separated word."""
    def __call__(self, text, add_special_tokens=False):
        return {"input_ids": text.split()}

    def decode(self, ids):
        return " ".join(ids)


@pytest.fixture
def stub_stream(monkeypatch):
    import datasets

    from hls.spec.datasets import _TOKENIZER_CACHE
    monkeypatch.setitem(_TOKENIZER_CACHE, ("Qwen/Qwen2.5-32B", "main"), _WordTokenizer())

    def _install(rows):
        monkeypatch.setattr(datasets, "load_dataset", lambda *a, **k: rows)
    return _install


def _file(name, *, license="mit", tokens=40, autogenerated=False):
    return {"hash": zlib.crc32(name.encode()), "license": license,
            "autogenerated": autogenerated,
            "content": " ".join(f"{name}{i}" for i in range(tokens))}


def _small(**kw):
    return _ds(subsample_size=10, min_prefix_tokens=4, max_prefix_tokens=8,
               target_tokens=2, **kw)


def test_corpus_keeps_only_permissively_licensed_files(stub_stream):
    stub_stream([_file("gpl", license="gpl-3.0"), _file("mit")])
    rows = _small().corpus().to_list()
    assert len(rows) == 1 and "mit0" in rows[0]["prompt"]


def test_corpus_drops_autogenerated_files(stub_stream):
    stub_stream([_file("gen", autogenerated=True), _file("hand")])
    rows = _small().corpus().to_list()
    assert len(rows) == 1 and "hand0" in rows[0]["prompt"]


def test_corpus_drops_files_shorter_than_the_window_plus_target(stub_stream):
    """Every kept file must survive the LONGEST prefix draw and still leave a real
    continuation, or the ground truth would be empty for some draws."""
    stub_stream([_file("tiny", tokens=9), _file("big", tokens=40)])
    rows = _small().corpus().to_list()
    assert len(rows) == 1 and "big0" in rows[0]["prompt"]


def test_corpus_cuts_at_the_seeded_window_and_targets_the_continuation(stub_stream):
    ds = _small()
    stub_stream([_file("f", tokens=40)])
    row = ds.corpus().to_list()[0]

    n = ds.prefix_tokens(ds.min_prefix_tokens, ds.max_prefix_tokens,
                         ds.truncation_seed, 0)
    prefix = row["prompt"].removeprefix(f"{CODE_COMPLETION_INSTRUCTION}\n\n")
    assert prefix.split() == [f"f{i}" for i in range(n)]
    assert row["target"].split() == [f"f{n}", f"f{n + 1}"]


def test_corpus_is_deterministic_across_runs(stub_stream):
    files = [_file(f"f{j}", tokens=40) for j in range(5)]
    stub_stream(files)
    first = _small().corpus().to_list()
    stub_stream(files)
    assert _small().corpus().to_list() == first


def test_corpus_id_carries_the_filters_that_shape_the_pool():
    cid = _ds(subsample_size=1875).corpus_id()
    for part in ("lic=apache-2.0", "n=1875", "win=1024-3072", "tgt=64", "seed=20260727"):
        assert part in cid


def test_license_allowlist_is_permissive_only():
    """The corpus mixes permissive and copyleft repos in one `license` column; the
    allowlist is what keeps the served prompts permissively licensed."""
    licenses = set(_ds().licenses)
    assert licenses == {"mit", "apache-2.0", "bsd-3-clause", "bsd-2-clause", "isc"}
    assert not any(lic.startswith(("gpl", "agpl", "lgpl")) for lic in licenses)


def test_unmounted_split_fails_loud(tmp_path):
    with pytest.raises(FileNotFoundError, match="(?i)test split not mounted"):
        list(_ds().items_at(tmp_path, Split.TEST))
